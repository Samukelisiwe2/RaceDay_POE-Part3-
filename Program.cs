
using System.IO;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.OpenApi;
using RaceDay.Data;

var builder = WebApplication.CreateBuilder(args);

// ==========================================
// 1. DATABASE CONFIGURATION
// ==========================================

var connectionString =
    builder.Configuration.GetConnectionString("DefaultConnection")
    ?? throw new InvalidOperationException(
        "Connection string 'DefaultConnection' not found.");

builder.Services.AddDbContext<ApplicationDbContext>(options =>
    options.UseSqlServer(connectionString));

builder.Services.AddDatabaseDeveloperPageExceptionFilter();

// ==========================================
// 2. ASP.NET CORE IDENTITY
// ==========================================

builder.Services.AddDefaultIdentity<IdentityUser>(options =>
{
    options.SignIn.RequireConfirmedAccount = true;
})
.AddRoles<IdentityRole>()
.AddEntityFrameworkStores<ApplicationDbContext>();

// ==========================================
// 3. MVC AND RAZOR PAGES
// ==========================================

builder.Services.AddControllersWithViews();
builder.Services.AddRazorPages();

// ==========================================
// 4. SWAGGER CONFIGURATION
// ==========================================

builder.Services.AddEndpointsApiExplorer();

builder.Services.AddSwaggerGen(options =>
{
    options.SwaggerDoc("v1", new OpenApiInfo
    {
        Title = "RaceDay API",
        Version = "v1",
        Description =
            "RaceDay API documentation for PROG6212 Part 2. " +
            "The API supports authentication, user profiles, " +
            "race events, categories, participant enrolments, " +
            "race results and role-based authorization."
    });

    // Load XML comments into Swagger.
    // Generated by RaceDay.csproj during build.

    var xmlFile =
        $"{typeof(Program).Assembly.GetName().Name}.xml";

    var xmlPath =
        Path.Combine(AppContext.BaseDirectory, xmlFile);

    if (File.Exists(xmlPath))
    {
        options.IncludeXmlComments(xmlPath);
    }
});

// ==========================================
// 5. BUILD APPLICATION
// ==========================================

var app = builder.Build();

// ==========================================
// 6. INTEGRATION TEST CONFIGURATION
// ==========================================

// Integration tests use an isolated SQLite database.
// Normal SQL Server migrations and Admin seeding
// are skipped while integration tests are running.

var isIntegrationTest =
    app.Configuration.GetValue<bool>(
        "RaceDay:IntegrationTesting");

// ==========================================
// 7. DATABASE MIGRATIONS AND ROLE SEEDING
// ==========================================

if (!isIntegrationTest)
{
    using var scope = app.Services.CreateScope();

    var services = scope.ServiceProvider;

    var db = services
        .GetRequiredService<ApplicationDbContext>();

    // Apply pending SQL Server migrations.
    await db.Database.MigrateAsync();

    // ======================================
    // CREATE APPLICATION ROLES
    // ======================================

    var roleManager = services
        .GetRequiredService<RoleManager<IdentityRole>>();

    string[] roles =
    {
        "Admin",
        "Organiser",
        "Participant"
    };

    foreach (var role in roles)
    {
        if (!await roleManager.RoleExistsAsync(role))
        {
            var roleResult =
                await roleManager.CreateAsync(
                    new IdentityRole(role));

            if (!roleResult.Succeeded)
            {
                throw new InvalidOperationException(
                    $"Failed to create role '{role}': " +
                    string.Join(", ",
                        roleResult.Errors.Select(
                            e => e.Description)));
            }
        }
    }

    // ======================================
    // 8. ADMIN ACCOUNT SEEDING
    // ======================================

    var userManager = services
        .GetRequiredService<UserManager<IdentityUser>>();

    // Credentials are read from configuration
    // and are never hard-coded in this file.

    string? adminEmail =
        app.Configuration["SeedAdmin:Email"];

    string? adminPassword =
        app.Configuration["SeedAdmin:Password"];

    // Only seed Admin when email is configured.
    if (!string.IsNullOrWhiteSpace(adminEmail))
    {
        var adminUser =
            await userManager.FindByEmailAsync(adminEmail);

        // Create account only when missing.
        if (adminUser == null)
        {
            if (string.IsNullOrWhiteSpace(adminPassword))
            {
                throw new InvalidOperationException(
                    "SeedAdmin:Password must be configured " +
                    "before creating an Admin account.");
            }

            adminUser = new IdentityUser
            {
                UserName = adminEmail,
                Email = adminEmail,
                EmailConfirmed = true
            };

            var createResult =
                await userManager.CreateAsync(
                    adminUser,
                    adminPassword);

            if (!createResult.Succeeded)
            {
                throw new InvalidOperationException(
                    "Failed to create Admin account: " +
                    string.Join(", ",
                        createResult.Errors.Select(
                            e => e.Description)));
            }
        }

        // Ensure the existing account has Admin role.
        if (!await userManager.IsInRoleAsync(
            adminUser, "Admin"))
        {
            var roleResult =
                await userManager.AddToRoleAsync(
                    adminUser,
                    "Admin");

            if (!roleResult.Succeeded)
            {
                throw new InvalidOperationException(
                    "Failed to assign Admin role: " +
                    string.Join(", ",
                        roleResult.Errors.Select(
                            e => e.Description)));
            }
        }
    }
}

// ==========================================
// 9. HTTP REQUEST PIPELINE
// ==========================================

if (app.Environment.IsDevelopment())
{
    if (!isIntegrationTest)
    {
        app.UseMigrationsEndPoint();
    }

    // Serve Swagger JSON and UI in Development.
    app.UseSwagger();

    app.UseSwaggerUI(options =>
    {
        options.SwaggerEndpoint(
            "/swagger/v1/swagger.json",
            "RaceDay API v1");

        options.DocumentTitle =
            "RaceDay API - Swagger Documentation";
    });
}
else
{
    app.UseExceptionHandler("/Home/Error");
    app.UseHsts();
}

// ==========================================
// 10. MIDDLEWARE
// ==========================================

app.UseHttpsRedirection();

app.UseRouting();

// Authentication must precede authorization.
app.UseAuthentication();
app.UseAuthorization();

// ==========================================
// 11. ROUTING
// ==========================================

app.MapStaticAssets();

// MVC controllers and views.
app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}")
    .WithStaticAssets();

// ASP.NET Core Identity Razor Pages.
app.MapRazorPages()
    .WithStaticAssets();

// Attribute-routed API controllers.
app.MapControllers();

// ==========================================
// 12. START RACEDAY
// ==========================================

app.Run();

// Required for WebApplicationFactory integration tests.
public partial class Program
{
}


